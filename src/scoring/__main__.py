"""Score the demo and run the core-claim sweep:

python -m src.scoring [--deadline HH:MM] [--penalty 75] [--vot 30] [--seed 42] [--no-sweep]

Writes eval/core_claim.md (demo preset table + penalty × margin sweep).
"""

from __future__ import annotations

import argparse

import pandas as pd

from src import config
from src.contracts import ScoredOption
from src.scoring.pipeline import evaluate, load_demo_data, sweep
from src.scoring.scorer import Settings

CORE_CLAIM_MD = config.REPO_ROOT / "eval" / "core_claim.md"


def _hhmm(t) -> str:
    return "—" if t is None else pd.Timestamp(t).tz_convert(config.LOCAL_TZ).strftime("%H:%M")


def _usd(v: float | None) -> str:
    return "—" if v is None else f"{v:.2f}"


def table(scored: list[ScoredOption]) -> pd.DataFrame:
    rows = []
    for s in sorted(scored, key=lambda s: (s.rank is None, s.rank or 0)):
        c = s.candidate
        planned = c.planned_train
        rows.append({
            "rank": s.rank or "—", "sched_rank": s.sched_rank or "—", "candidate": s.candidate_id,
            "leave": _hhmm(c.leave_home), "planned": planned.train_number if planned else "—",
            "p_on_time": "—" if s.p_on_time is None else f"{s.p_on_time:.2f}",
            "arr_p50": _hhmm(s.arrival_p50), "arr_p90": _hhmm(s.arrival_p90),
            "e_late_min": "—" if s.expected_late_min is None else f"{s.expected_late_min:.1f}",
            "money": _usd(s.money_usd), "time_cost": _usd(s.time_cost_usd),
            "exp_late_cost": _usd(s.exp_late_cost_usd), "gen_cost": _usd(s.gen_cost_usd),
            "trains_taken": ", ".join(f"{k} {v:.0%}" for k, v in
                                      sorted(s.train_taken_share.items(), key=lambda kv: -kv[1])) or "—",
            "pools": ", ".join(f"{u.train_number}:{u.fallback_level.value}/{u.run_count}" for u in s.pools) or "—",
            "flags": ", ".join(sorted(s.flags)) or "—",
        })
    return pd.DataFrame(rows)


def markdown(df: pd.DataFrame) -> str:
    cells = [[str(v).replace("|", "/") for v in row] for row in df.itertuples(index=False)]
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    return "\n".join(lines + ["| " + " | ".join(r) + " |" for r in cells])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--deadline", default="09:00")
    parser.add_argument("--penalty", type=float, default=config.DEFAULT_HARD_PENALTY_USD)
    parser.add_argument("--vot", type=float, default=config.DEFAULT_VOT_USD_PER_H)
    parser.add_argument("--seed", type=int, default=config.DEFAULT_SEED)
    parser.add_argument("--no-sweep", action="store_true")
    args = parser.parse_args()
    h, m = map(int, args.deadline.split(":"))
    settings = Settings(deadline_s=h * 3600 + m * 60, hard_penalty_usd=args.penalty,
                        vot_usd_per_h=args.vot, seed=args.seed)
    data = load_demo_data()
    demo = table(evaluate(data, settings))
    pd.set_option("display.width", 250)
    print(demo.drop(columns=["pools"]).to_string(index=False))
    if args.no_sweep:
        return
    sw = sweep(data, settings)
    sw_out = sw.assign(p_on_time=sw["p_on_time"].map(
        lambda d: ", ".join(f"{k.split(' ')[0]}{'+PATH' if 'PATH' in k else ''} {v:.2f}" for k, v in d.items())))
    print(sw_out.to_string(index=False))
    flips = sw[sw["flips"]]
    CORE_CLAIM_MD.parent.mkdir(parents=True, exist_ok=True)
    CORE_CLAIM_MD.write_text(
        f"# Core claim check ({config.DEMO_SERVICE_DATE}, deadline {args.deadline} at NY Penn)\n\n"
        "Generated by `python -m src.scoring`. rank = generalized cost (money + VOT × door-to-deadline "
        "time + expected lateness cost); sched_rank = money + time only (no risk). "
        f"VOT ${settings.vot_usd_per_h:g}/h, N = {settings.n}, seed {settings.seed}. Drive-all-the-way is a "
        "reference row (not priced, not ranked); CM/ST/RT → NY have no train on 10-13.\n\n"
        f"## Demo preset (hard penalty ${settings.hard_penalty_usd:g}, margin {settings.margin_s // 60} min)\n\n"
        + markdown(demo) +
        "\n\n## Sweep: hard penalty × margin (leave_home re-planned per margin)\n\n" + markdown(sw_out) +
        f"\n\n**Top-1 differs in {len(flips)} of {len(sw)} settings.**\n\n"
        "Caveats: about one weekday of AM-peak data; CM → HB has only 5 effective runs (L1), so its "
        "P(on time) moves in steps of 1/5; PATH runs to schedule (not measured); cancelled runs are "
        "invisible; NY delay uses feed-relative SEC_LATE (provisional, check A).\n",
        encoding="utf-8")
    print(f"wrote {CORE_CLAIM_MD}")


if __name__ == "__main__":
    main()
